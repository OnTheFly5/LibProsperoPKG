using LibProsperoPkg.PFS;
using LibProsperoPkg.PKG;
using LibProsperoPkg.Util;
using System.Buffers.Binary;
using System.Security.Cryptography;

namespace LibProsperoPkg.Tests;

internal static class OuterStreamingTests
{
    private const int B = 0x10000;
    private const int P = B / 36;
    private static readonly byte[] Key = Enumerable.Range(0, 32).Select(i => (byte)i).ToArray();
    private static readonly ProsperoOuterPfsBuildParameters Parameters = new()
    {
        Seed = Enumerable.Range(32, 16).Select(i => (byte)i).ToArray(),
        TimestampSeconds = 12345678, TimestampNanoseconds = 123456,
    };

    internal static void Run()
    {
        MatchesBufferedImage();
        NestedInnerImage();
        DoubleIndirectImage();
        LayoutBounds();
        ErrorsAndCancellation();
    }

    private static void Same(ReadOnlySpan<byte> expected, ReadOnlySpan<byte> actual, string context)
        => Program.Equal(true, expected.SequenceEqual(actual), context);

    private static void MatchesBufferedImage()
    {
        foreach (int length in new[] { 0, 1, 12 * B, 13 * B + 17 })
        {
            byte[] content = new byte[length];
            new Random(42).NextBytes(content);
            byte[] naps = new byte[] { 7, 8, 9 };
            var files = new[]
            {
                new ProsperoOuterFile { Name = "pfs_image.dat", Data = content, SizeCompressed = length + 1000L },
                new ProsperoOuterFile { Name = "naps_pkg_layout.dat", Data = naps, Signed = true },
            };
            var expected = ProsperoOuterPfsBuilder.BuildForPackage(files, Parameters, Key);
            if (length == 13 * B + 17)
            {
                // Independently generated by the pinned 61cb08f buffered writer.
                Program.Equal("1387AB54DA64B267A3A8BAB1964CD889F6D7466154F094301B4F6DE61E6B83BC",
                    Convert.ToHexString(SHA256.HashData(expected.Ciphertext)), "pinned outer-image fixture");
            }
            using var bytes = new MemoryStream();
            // The encrypted image's sector indexes are relative to the image, not this prefix.
            bytes.Write(new byte[] { 1, 2, 3 });
            using var output = new AppendOnlyDestination(bytes);
            int invocations = 0;
            Stream? retained = null;
            var result = ProsperoOuterPfsBuilder.WriteForPackage(output, new[]
            {
                new ProsperoOuterFileProducer
                {
                    Name = "pfs_image.dat", WritePayload = sink =>
                    {
                        invocations++;
                        retained = sink;
                        Program.Equal(false, sink.CanSeek, "producer cannot seek");
                        Program.Throws<NotSupportedException>(() => _ = sink.Position);
                        // Flush midway through a partial block must not insert padding.
                        for (int offset = 0; offset < content.Length; offset += 997)
                        {
                            sink.Write(content.AsSpan(offset, Math.Min(997, content.Length - offset)));
                            sink.Flush();
                        }
                        return length + 1000L;
                    },
                },
                new ProsperoOuterFileProducer { Name = "naps_pkg_layout.dat", Signed = true,
                    WritePayload = sink => { sink.Write(naps); return null; } },
            }, Parameters, Key);
            Same(expected.Ciphertext, bytes.ToArray().AsSpan(3), "outer ciphertext parity");
            Same(new byte[] { 1, 2, 3 }, bytes.ToArray().AsSpan(0, 3), "outer prefix preserved");
            Same(expected.SuperblockIcv, result.SuperblockIcv, "outer ICV parity");
            Program.Equal(expected.PfsSize, result.PfsSize, "outer size parity");
            Program.Equal(expected.SuperblockIndex, result.SuperblockIndex, "outer superblock index");
            for (int i = 0; i < result.BlockCount; i++)
                Same(expected.ImageDigests.AsSpan(i * 32, 32), result.GetBlockDigest(i).Span, "outer digest parity");
            Program.Equal(1, invocations, "unknown length producer called once");
            Program.Equal(true, output.CanWrite, "destination remains open");
            Program.Equal(true, output.MaxWrite <= B, "bounded destination write");
            Program.Throws<ObjectDisposedException>(() => retained!.WriteByte(0));
            Program.Throws<ArgumentOutOfRangeException>(() => result.GetBlockDigest(-1));
            Program.Throws<ArgumentOutOfRangeException>(() => result.GetBlockDigest(result.BlockCount));
        }
    }

    private static void NestedInnerImage()
    {
        byte[] content = new byte[0x80000 + 17];
        new Random(43).NextBytes(content);
        // Mixed stored/compressed codec blocks, with geometry discovered inside the outer producer.
        content.AsSpan(0, 0x40000).Fill(0x55);
        var assembler = new ProsperoPs5InnerImageAssembler(12345678, 123456);
        var buffered = assembler.Build(new[] { new ProsperoPs5InnerFile { Path = "/asset.bin", Data = content } });
        byte[] naps = ProsperoNwonlyNapsGenerator.Generate(buffered);
        var expected = ProsperoOuterPfsBuilder.BuildForPackage(new[]
        {
            new ProsperoOuterFile { Name = "pfs_image.dat", Data = buffered.Image, SizeCompressed = buffered.Ndblock * B },
            new ProsperoOuterFile { Name = "naps_pkg_layout.dat", Data = naps, Signed = true },
        }, Parameters, Key);
        int opens = 0;
        ProsperoPs5InnerImageLayout? inner = null;
        using var bytes = new MemoryStream();
        using var output = new AppendOnlyDestination(bytes);
        var result = ProsperoOuterPfsBuilder.WriteForPackage(output, new[]
        {
            new ProsperoOuterFileProducer { Name = "pfs_image.dat", WritePayload = sink =>
            {
                inner = assembler.Write(sink, new[]
                {
                    new ProsperoPs5InnerFileSource { Path = "/asset.bin", Length = content.LongLength,
                        OpenRead = () => { opens++; return new MemoryStream(content, false); } },
                });
                return inner.Ndblock * B;
            } },
            new ProsperoOuterFileProducer { Name = "naps_pkg_layout.dat", Signed = true, WritePayload = sink =>
            {
                sink.Write(ProsperoNwonlyNapsGenerator.Generate(inner!));
                return null;
            } },
        }, Parameters, Key);
        Program.Equal(1, opens, "nested inner source opened once");
        Program.Equal(buffered.Image.LongLength, result.FileSize[0], "nested inner physical size");
        Same(expected.Ciphertext, bytes.ToArray(), "nested inner/NAPS/outer streaming parity");
    }

    private static void DoubleIndirectImage()
    {
        const int n = 12 + P + 1; // first double-indirect pointer, immediately after single capacity
        byte[] data = Enumerable.Range(0, B).Select(i => (byte)(i * 13 + 7)).ToArray();
        byte[] expectedDataHash = ProsperoOuterPfsSignature.ComputeBlockHash(data);
        using var output = new SamplingDestination(n);
        long baseline = GC.GetTotalMemory(true);
        long liveGrowth = 0;
        var result = ProsperoOuterPfsBuilder.WriteForPackage(output, new[]
        {
            new ProsperoOuterFileProducer { Name = "pfs_image.dat", WritePayload = sink =>
            {
                for (int i = 0; i < n; i++) sink.Write(data);
                liveGrowth = GC.GetTotalMemory(true) - baseline;
                return n * (long)B + 200;
            } },
        }, Parameters, Key);
        Program.Equal(true, liveGrowth < 8 * 1024 * 1024, "live memory bounded by metadata, not 114 MiB payload");
        Program.Equal((long)n * B, result.FileSize[0], "unknown length recorded as Int64");
        Program.Equal((long)n * B + 200, result.FileSizeCompressed[0], "logical size recorded separately");
        Program.Equal(n, result.SuperblockIndex, "data-first superblock");
        Program.Equal(n + 8, result.BlockCount, "single plus double root and one leaf");
        Program.Equal(true, output.MaxWrite <= B, "large image writes bounded");
        for (int i = 0; i < n; i++) Same(expectedDataHash, result.GetBlockDigest(i).Span, "all data hashes");
        // Independent tweak construction; using the same plaintext at indexes 0 and 12 must differ.
        Program.Equal(false, output.Captured[0].AsSpan().SequenceEqual(output.Captured[12]), "absolute XTS sectors differ");
        var (tweak, key) = ProsperoPfsKeys.DeriveImageEncryptionKeys(Key, Parameters.Seed!);
        using var xts = new XtsBlockTransform(key, tweak);
        byte[] Plain(int index, bool signed)
        {
            var block = output.Captured[index].ToArray();
            xts.CryptSector(block, (signed ? 1UL << 47 : 0) | (uint)index, false);
            return block;
        }
        Same(data, Plain(0, false), "first data sector");
        Same(data, Plain(12, false), "later data sector");
        Same(data, Plain(n - 1, false), "last data sector");
        byte[] inodeBlock = Plain(n + 1, true);
        using var inodeStream = new MemoryStream(inodeBlock);
        inodeStream.Position = 3 * ProsperoDinodeS32.SizeOf;
        var inode = ProsperoDinodeS32.ReadFromStream(inodeStream);
        Program.Equal((uint)n, inode.Blocks, "inode block count excludes indirect metadata");
        Program.Equal(n * (long)B, inode.Size, "inode physical size");
        for (int j = 0; j < 12; j++)
        {
            Program.Equal(j, inode.db[j].block, "direct pointer order");
            Same(expectedDataHash, inode.db[j].sig, "direct pointer digest");
        }
        byte[] ReadPointer(ProsperoBlockSig pointer)
        {
            byte[] block = Plain(pointer.block, true);
            Same(ProsperoOuterPfsSignature.ComputeBlockHash(block), pointer.sig, "indirect parent authenticates child");
            return block;
        }
        byte[] single = ReadPointer(inode.ib[0]);
        for (int j = 0; j < P; j++)
        {
            Program.Equal(12 + j, BinaryPrimitives.ReadInt32LittleEndian(single.AsSpan(j * 36 + 32)), "single pointer order");
            Same(expectedDataHash, single.AsSpan(j * 36, 32), "single child hash");
        }
        Program.Equal(true, single.AsSpan(P * 36).IndexOfAnyExcept((byte)0) < 0, "single slack zeroed");
        byte[] parent = ReadPointer(inode.ib[1]);
        var leafPointer = new ProsperoBlockSig
        {
            sig = parent.AsSpan(0, 32).ToArray(), block = BinaryPrimitives.ReadInt32LittleEndian(parent.AsSpan(32)),
        };
        byte[] leaf = ReadPointer(leafPointer);
        Program.Equal(n - 1, BinaryPrimitives.ReadInt32LittleEndian(leaf.AsSpan(32)), "double leaf points to last data");
        Same(expectedDataHash, leaf.AsSpan(0, 32), "double leaf child digest");
        Program.Equal(true, leaf.AsSpan(36).IndexOfAnyExcept((byte)0) < 0, "double leaf unused slots zero");
        Program.Equal(true, parent.AsSpan(36).IndexOfAnyExcept((byte)0) < 0, "double parent unused slots zero");
        for (int i = 2; i < 5; i++)
        {
            Program.Equal(0, inode.ib[i].block, "unimplemented higher indirect slots zero");
            Program.Equal(true, inode.ib[i].sig.AsSpan().IndexOfAnyExcept((byte)0) < 0, "higher indirect hashes zero");
        }
        byte[] sb = output.Captured[n]; // stored unencrypted
        Same(result.SuperblockIcv, ProsperoOuterPfsSignature.ComputeSuperblockIcv(sb), "streamed clear superblock ICV");
        Same(ProsperoOuterPfsSignature.ComputeBlockHash(inodeBlock), sb.AsSpan(0xb8, 32), "superblock inode-table digest");
        foreach (int i in output.Captured.Keys.Where(i => i >= n))
        {
            byte[] plain = i == n ? output.Captured[i] : Plain(i, true);
            Same(ProsperoOuterPfsSignature.ComputeBlockHash(plain), result.GetBlockDigest(i).Span, "metadata digests are plaintext hashes");
        }
    }

    private static void LayoutBounds()
    {
        foreach (var (blocks, expected) in new[] { (12L, 0), (13L, 1), (1832L, 1), (1833L, 3), (9113L, 7), (3314232L, 1822) })
            Program.Equal(expected, ProsperoOuterPfsBuilder.GetStreamedIndirectBlockCount(blocks * B), "sizing-only indirect count");
        Program.Equal(0, ProsperoOuterPfsBuilder.GetStreamedIndirectBlockCount(0), "empty file needs no indirect blocks");
        Program.Throws<ArgumentOutOfRangeException>(() => ProsperoOuterPfsBuilder.GetStreamedIndirectBlockCount(-1));
        Program.Throws<ArgumentOutOfRangeException>(() => ProsperoOuterPfsBuilder.GetStreamedIndirectBlockCount(
            ProsperoOuterPfsBuilder.MaximumStreamedFileSize + 1));
    }

    private static void ErrorsAndCancellation()
    {
        using var output = new AppendOnlyDestination(Stream.Null);
        int later = 0;
        var fail = new ProsperoOuterFileProducer { Name = "pfs_image.dat", WritePayload = sink =>
        {
            sink.Write(new byte[] { 1 });
            throw new InvalidDataException("producer failure");
        } };
        var second = new ProsperoOuterFileProducer { Name = "naps_pkg_layout.dat", WritePayload = sink => { later++; return null; } };
        Program.Throws<InvalidDataException>(() => ProsperoOuterPfsBuilder.WriteForPackage(output, new[] { fail, second }, Parameters, Key));
        Program.Equal(0, later, "producer failure stops pipeline");
        Program.Equal(0L, output.BytesWritten, "failed partial file never gets padded or finalized");
        using var cts = new CancellationTokenSource();
        var cancel = new ProsperoOuterFileProducer { Name = "pfs_image.dat", WritePayload = sink =>
        {
            sink.WriteByte(1);
            cts.Cancel();
            return null;
        } };
        Program.Throws<OperationCanceledException>(() => ProsperoOuterPfsBuilder.WriteForPackage(output, new[] { cancel, second }, Parameters, Key, cts.Token));
        Program.Equal(0, later, "cancel stops before next producer");
        Program.Equal(0L, output.BytesWritten, "cancel does not finalize metadata");
        Program.Equal(true, output.CanWrite, "failure leaves destination open");
        var empty = new ProsperoOuterFileProducer { Name = "game", WritePayload = sink => null };
        foreach (string invalid in new[] { "../game", "gáme", "", ".", "..", "a\\b" })
        {
            var bad = new ProsperoOuterFileProducer { Name = invalid, WritePayload = sink => { later++; return null; } };
            Program.Throws<ArgumentException>(() => ProsperoOuterPfsBuilder.WriteForPackage(output, new[] { bad }, Parameters, Key));
        }
        Program.Throws<ArgumentException>(() => ProsperoOuterPfsBuilder.WriteForPackage(output, new[] { empty, empty }, Parameters, Key));
        Program.Equal(0, later, "preflight rejects names before invoking producers");
        using var broken = new AppendOnlyDestination(Stream.Null) { FailWrites = true };
        var full = new ProsperoOuterFileProducer { Name = "game", WritePayload = sink => { sink.Write(new byte[B]); return null; } };
        Program.Throws<IOException>(() => ProsperoOuterPfsBuilder.WriteForPackage(broken, new[] { full, second }, Parameters, Key));
        Program.Equal(0, later, "output error stops remaining producers");
        Program.Equal(true, broken.CanWrite, "output failure does not dispose caller stream");
        using var transient = new FailOnceDestination();
        var swallowsError = new ProsperoOuterFileProducer { Name = "game", WritePayload = sink =>
        {
            try { sink.Write(new byte[B]); }
            catch (IOException) { /* A callback cannot suppress a transport failure. */ }
            Program.Throws<IOException>(() => sink.WriteByte(1));
            return null;
        } };
        Program.Throws<IOException>(() => ProsperoOuterPfsBuilder.WriteForPackage(transient,
            new[] { swallowsError, second }, Parameters, Key));
        Program.Equal(1, transient.Attempts, "failed encrypted block never retried");
        Program.Equal(0, later, "swallowed write failure still aborts pipeline");

    }

    private class AppendOnlyDestination(Stream target) : Stream
    {
        public int MaxWrite { get; private set; }
        public long BytesWritten { get; private set; }
        public bool FailWrites { get; init; }
        public override void Write(byte[] buffer, int offset, int count) => Write(buffer.AsSpan(offset, count));
        public override void Write(ReadOnlySpan<byte> bytes)
        {
            if (FailWrites) throw new IOException("destination failure");
            MaxWrite = Math.Max(MaxWrite, bytes.Length);
            target.Write(bytes);
            BytesWritten += bytes.Length;
        }
        public override bool CanRead => false;
        public override bool CanSeek => false;
        public override bool CanWrite => true;
        public override long Length => throw new NotSupportedException();
        public override long Position { get => throw new NotSupportedException(); set => throw new NotSupportedException(); }
        public override void Flush() { }
        public override int Read(byte[] buffer, int offset, int count) => throw new NotSupportedException();
        public override long Seek(long offset, SeekOrigin origin) => throw new NotSupportedException();
        public override void SetLength(long value) => throw new NotSupportedException();
    }

    private sealed class FailOnceDestination() : AppendOnlyDestination(Stream.Null)
    {
        internal int Attempts { get; private set; }
        public override void Write(ReadOnlySpan<byte> bytes)
        {
            if (++Attempts == 1) throw new IOException("transient transport failure");
            base.Write(bytes);
        }
    }

    private sealed class SamplingDestination(int dataBlocks) : AppendOnlyDestination(Stream.Null)
    {
        internal Dictionary<int, byte[]> Captured { get; } = new();
        public override void Write(ReadOnlySpan<byte> bytes)
        {
            int index = checked((int)(BytesWritten / B));
            Program.Equal(B, bytes.Length, "one complete block per emission");
            if (index >= dataBlocks || index == 0 || index == 12 || index == dataBlocks - 1)
                Captured.Add(index, bytes.ToArray());
            base.Write(bytes);
        }
    }
}
